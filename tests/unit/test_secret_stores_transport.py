def test_open_needs_a_private_key_object_and_bytes_aad(pair):
    private, public = pair
    sealed = transport.seal(PLAINTEXT, public, AAD.encode())
    for bad_key in (None, "key", private.public_key(), base64.b64encode(bytes(32))):
        with pytest.raises(transport.TransportError):
            transport.open_sealed(sealed, bad_key, AAD.encode())
    with pytest.raises(transport.TransportError):
        transport.open_sealed(sealed, private, AAD)  # str aad


@pytest.mark.parametrize("key", [None, "", "not base64!", "AAAA", base64.b64encode(bytes(31)).decode(),
                                 base64.b64encode(bytes(33)).decode(), base64.b64encode(bytes(32)).decode()])
def test_bad_recipient_key_is_refused(key):
    with pytest.raises(transport.TransportError):
        transport.seal(PLAINTEXT, key, AAD.encode())


def test_seal_needs_bytes(pair):
    _, public = pair
    for plaintext, aad in ((MARKER, AAD.encode()), (PLAINTEXT, AAD), (None, AAD.encode()), (PLAINTEXT, None)):
        with pytest.raises(transport.TransportError):
            transport.seal(plaintext, public, aad)


# -- shared vector -----------------------------------------------------------------------------


def _vector_private():
    return X25519PrivateKey.from_private_bytes(base64.b64decode(VECTOR["recipient_private_key"]))


def test_vector_decrypts():
    plaintext = transport.open_sealed(VECTOR["sealed"], _vector_private(), VECTOR["aad"].encode())
    assert plaintext == VECTOR["plaintext"].encode()
    assert json.loads(plaintext)["fields"] == {"access_token": "test-value"}


def test_vector_regenerates_exactly():
    sealed = transport.seal(
        VECTOR["plaintext"].encode(), VECTOR["recipient_public_key"], VECTOR["aad"].encode(),
        _ephemeral_private_key=X25519PrivateKey.from_private_bytes(base64.b64decode(VECTOR["ephemeral_private_key"])),
        _nonce=base64.b64decode(VECTOR["nonce"]))
    assert sealed == VECTOR["sealed"]


def test_vector_fails_with_other_aad_or_key():
    with pytest.raises(transport.TransportError):
        transport.open_sealed(VECTOR["sealed"], _vector_private(), VECTOR["aad"].encode() + b"x")
    with pytest.raises(transport.TransportError):
        transport.open_sealed(VECTOR["sealed"], transport.generate_recipient_keypair()[0], VECTOR["aad"].encode())


def test_fixed_nonce_must_be_twelve_bytes(pair):
    with pytest.raises(transport.TransportError):
        transport.seal(PLAINTEXT, pair[1], AAD.encode(), _nonce=b"short")


# -- no plaintext anywhere it should not be ----------------------------------------------------


def test_nothing_exposes_plaintext(pair):
    private, public = pair
    sealed = transport.seal(PLAINTEXT, public, AAD.encode())
    texts = [repr(sealed), str(sealed), json.dumps(sealed), repr(private), repr(public), repr(transport)]
    for bad in (_tamper(sealed, "ct"), {**sealed, "v": 2}, {**sealed, "epk": "AAAA"}):
        with pytest.raises(transport.TransportError) as raised:
            transport.open_sealed(bad, private, AAD.encode())
        texts += [repr(raised.value), str(raised.value), "".join(traceback.format_exception(raised.value))]
    with pytest.raises(transport.TransportError) as raised:
        transport.seal(PLAINTEXT, "nope", AAD.encode())
    texts += [repr(raised.value), "".join(traceback.format_exception(raised.value))]
    assert all(MARKER not in text and "access_token" not in text for text in texts)
    assert str(raised.value) == "credential transport failure"


def test_failures_do_not_say_which_part_was_wrong(pair):
    private, public = pair
    sealed = transport.seal(PLAINTEXT, public, AAD.encode())
    failures = set()
    for bad, aad in ((_tamper(sealed, "ct"), AAD.encode()), (_tamper(sealed, "nonce"), AAD.encode()),
                     (_tamper(sealed, "epk"), AAD.encode()), (sealed, b"other"), ({**sealed, "v": 2}, AAD.encode())):
        with pytest.raises(transport.TransportError) as raised:
            transport.open_sealed(bad, private, aad)
        failures.add((type(raised.value), str(raised.value), raised.value.__cause__))
    assert len(failures) == 1


def test_module_defines_no_secret_holding_objects():
    # the module is three functions and an exception: no class instance that could hold plaintext
    assert sorted(name for name in vars(transport) if not name.startswith("_") and isinstance(
        getattr(transport, name), type) and getattr(transport, name).__module__ == transport.__name__
    ) == ["TransportError"]


# -- the release purpose -----------------------------------------------------------------------


def test_release_purpose_is_read_only():
    assert "release" in stores.PURPOSES
    allowed = {op for op, purposes in stores.OPERATION_PURPOSES.items() if "release" in purposes}
    assert allowed == {"read"}


def test_release_context_mints_and_is_read_only_on_a_store():
    ctx = mint(stores, "release", new_ref(stores))
    assert ctx.purpose == "release"
    ref = new_ref(stores)
    ctx = mint(stores, "release", ref)
    for operation in ("read", "write", "metadata", "delete_all"):
        if operation == "read":
            stores.check_context(ctx, ref, operation)
        else:
            with pytest.raises(stores.StoreError) as raised:
                stores.check_context(ctx, ref, operation)
            assert raised.value.code == "DENIED"
